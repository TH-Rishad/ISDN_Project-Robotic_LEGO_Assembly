"""Evaluate a controller on wriggle-fit contexts (WRIGGLE_FIT_RL.md §5).

Controllers: "scripted" (ScriptedWriggle), or a policy checkpoint from train_wriggle.py.
Contexts: "repo" (the held-out tight steps of the repo's assemblies), "family" (the socket
family's test split), "val" (its validation split, for checkpoint selection), or "probe" (the slot probe's pocket). Every context is run at each
aim-error level and brace condition ("none", "planner" = the repo plan's own brace,
"wriggle" = wriggle_brace's trigger with the ideal stand-in), for --seeds seeds.

    python eval_wriggle.py --controller scripted --contexts repo --levels 0 2 --seeds 3
    python eval_wriggle.py --controller results/runs/main/policy.pt --contexts repo family
    python eval_wriggle.py --controller scripted --sensing ft --no-fingers ...   # ablations
Writes Tanvir/results/eval/<tag>.jsonl (one row per episode) and <tag>.md (tables).
"""

import argparse
import json
import multiprocessing as mp
import os
import sys
import time
from collections import defaultdict
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import numpy as np                                         # noqa: E402

import socket_env as SE                                    # noqa: E402
import socket_family as SF                                 # noqa: E402
import wriggle_brace as WB                                 # noqa: E402

OUT = HERE / "results" / "eval"
BRACE_MODE = {"none": "none", "planner": "planner", "wriggle": "ideal"}


def contexts(kinds, per_class):
    out = []
    for k in kinds:
        if k == "repo":
            out += SF.repo_contexts()
        elif k in ("family", "val"):
            out += [c for cs in SF.pool("test" if k == "family" else "val", per_class).values() for c in cs]
        elif k == "probe":
            out.append(WB.probe_pocket())
    return out


_POLICY = {}


def _job(job):
    os.environ["OMP_NUM_THREADS"] = "1"
    ctx, level, brace, seed, ctrl, sensing, fingers = job
    if ctrl == "scripted":
        env = SE.SocketInsertionEnv(mode="scripted", sensing=sensing, seed=seed, fingers=fingers)
        policy = None
    else:
        import torch
        torch.set_num_threads(1)
        from train_wriggle import Policy
        if ctrl not in _POLICY:
            _POLICY[ctrl] = Policy(ctrl)
        policy = _POLICY[ctrl]
        env = SE.SocketInsertionEnv(mode=policy.cfg["mode"], sensing=sensing, seed=seed, fingers=fingers,
                                    res_scale=policy.cfg.get("res_scale", 1.0),
                                    res_release=policy.cfg.get("res_release", True))
    info = SE.run_episode(env, policy, context=ctx, level=level, brace=BRACE_MODE[brace])
    info.update(brace_condition=brace, seed=seed, source=ctx.get("structure", "family"), kind=ctx.get("kind"))
    return info


def evaluate(ctl, ctxs, levels, braces, seeds, workers, sensing="cheap", fingers=True, progress=False):
    """Run every (context, brace, level, seed); returns one info row per episode."""
    jobs = []
    for ctx in ctxs:
        for brace in braces:
            if brace == "planner" and not ctx.get("planner_brace"):
                continue
            for level in levels:
                for s in range(seeds):
                    jobs.append((ctx, level, brace, 10_000 + s, ctl, sensing, fingers))
    t0 = time.time()
    if progress:
        print("%d episodes on %d workers" % (len(jobs), workers), flush=True)
    rows = []
    with mp.get_context("spawn").Pool(workers) as pool:
        for n, info in enumerate(pool.imap_unordered(_job, jobs, chunksize=1)):
            rows.append(info)
            if progress and (n + 1) % 25 == 0:
                print("  %d/%d  seated %d  %.0fs" % (n + 1, len(jobs), sum(r["success"] for r in rows),
                                                      time.time() - t0), flush=True)
    return rows


def _rate(rows):
    return "%d/%d" % (sum(r["success"] for r in rows), len(rows)) if rows else "-"


def report(rows, tag, args):
    lines = ["# Wriggle-fit evaluation: %s" % tag, "",
             "Generated by `Tanvir/eval_wriggle.py` (%s). Controller `%s`, sensing `%s`, fingers %s." % (
                 time.strftime("%Y-%m-%d"), args.controller, args.sensing, not args.no_fingers),
             "Cells are seated / episodes. Aim-error level L draws the lateral error from U(previous level, level) mm: "
             + ", ".join("%d = %.1f mm" % (n, e) for n, e in enumerate(SE.ERR_LEVELS)) + ".", ""]
    levels = sorted({r["level"] for r in rows})
    braces = [b for b in BRACE_MODE if any(r["brace_condition"] == b for r in rows)]
    lines += ["## By socket class and aim-error level (all brace conditions)", "",
              "| class | " + " | ".join("level %d" % l for l in levels) + " | all |",
              "|---|" + "---|" * (len(levels) + 1)]
    for c in SF.CLASSES:
        rc = [r for r in rows if r["class"] == c]
        if rc:
            lines.append("| %s | %s | %s |" % (c, " | ".join(_rate([r for r in rc if r["level"] == l]) for l in levels),
                                               _rate(rc)))
    lines += ["", "## By brace condition", "",
              "| brace | seated | joint breaks | arm contact | force over budget | timeouts | lost brick | mean peak force (N) | mean peak structure utilisation |",
              "|---|---|---|---|---|---|---|---|---|"]
    for b in braces:
        rb = [r for r in rows if r["brace_condition"] == b]
        cnt = lambda reason: sum(r["reason"] == reason for r in rb)
        lines.append("| %s | %s | %d | %d | %d | %d | %d | %.0f | %.2f |" % (
            b, _rate(rb), cnt("joint_break"), cnt("arm_contact"), cnt("force_violation"), cnt("timeout"),
            cnt("lost_brick"), np.mean([r["peak_force_N"] for r in rb]), np.mean([r["u_struct_peak"] for r in rb])))
    lines += ["", "## By context", "", "| context | class | " + " | ".join(braces) + " |", "|---|---|" + "---|" * len(braces)]
    by_ctx = defaultdict(list)
    for r in rows:
        by_ctx[r["context"]].append(r)
    for cid, rc in by_ctx.items():
        lines.append("| %s | %s | %s |" % (cid, rc[0]["class"], " | ".join(_rate([r for r in rc if r["brace_condition"] == b])
                                                                         for b in braces)))
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--controller", default="scripted")
    ap.add_argument("--contexts", nargs="+", default=["repo"], choices=["repo", "family", "val", "probe"])
    ap.add_argument("--per-class", type=int, default=5, help="family test contexts per class")
    ap.add_argument("--levels", type=int, nargs="+", default=[0, 2, 4])
    ap.add_argument("--braces", nargs="+", default=["none", "wriggle"], choices=list(BRACE_MODE))
    ap.add_argument("--seeds", type=int, default=2)
    ap.add_argument("--sensing", choices=["cheap", "ft", "none"], default="cheap")
    ap.add_argument("--no-fingers", action="store_true")
    ap.add_argument("--workers", type=int, default=7)
    ap.add_argument("--tag", default=None)
    args = ap.parse_args()
    ctl = args.controller if args.controller == "scripted" else str(Path(args.controller).resolve())
    tag = args.tag or "%s_%s_%s%s" % (Path(args.controller).parent.name if ctl != "scripted" else "scripted",
                                      "-".join(args.contexts), args.sensing, "_nofingers" if args.no_fingers else "")
    rows = evaluate(ctl, contexts(args.contexts, args.per_class), args.levels, args.braces, args.seeds,
                    args.workers, args.sensing, not args.no_fingers, progress=True)
    OUT.mkdir(parents=True, exist_ok=True)
    with open(OUT / (tag + ".jsonl"), "w") as f:
        for r in rows:
            f.write(json.dumps(r) + "\n")
    md = report(rows, tag, args)
    (OUT / (tag + ".md")).write_text(md)
    print(md)


if __name__ == "__main__":
    main()
