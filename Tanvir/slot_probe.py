"""Slot probe: where does the scripted wiggle stop working in a tight socket?

Runs the v3.1 MuJoCo twin's insertion cell (Sakib/brickassembly/tasks/insertion_env.py)
with its scripted base controller only (zero residual), aimed at a target that is
off by a fixed lateral error, in two sockets:

    open    no neighbours (InsertionEnv stage 0 layout)
    pocket  three flush neighbours, -y, +y and +x (stage 3 layout): two opposite faces
            leave 0.1 mm of play per side along y

and counts brick-to-neighbour contacts, so the slot is shown to be modelled rather
than assumed. --brace all stands in for the bracing arm (arm A) holding the
neighbours: their stud joints are made 10x stronger (an optimistic upper bound on a
real brace, which holds one or two bricks), and which neighbour breaks is recorded. Read-only on Sakib/; writes only Tanvir/results/slot_probe.md.

    python slot_probe.py                       # 0, 1, 2, 3, 4 mm x 6 seeds
    python slot_probe.py --errors 1 3 --seeds 3
    python slot_probe.py --brace none all      # unbraced vs braced neighbours

Needs numpy, scipy, mujoco (any 3.3+). About 1-2 s of CPU per episode.
"""

import argparse
import math
import sys
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "Sakib" / "brickassembly"))

import numpy as np                          # noqa: E402
import tasks.insertion_env as IE            # noqa: E402

LAYOUTS = {"open": 0, "pocket": 3}
BRACE_FACTOR = 10.0                         # braced neighbour joints: break force x this


def episode(layout, err_mm, seed, brace="none"):
    """One scripted episode; the believed target is off by err_mm in a seeded direction."""
    st = LAYOUTS[layout]
    IE.STAGES[st] = (0.002, math.radians(2), IE.STAGES[st][2], ["2x4"])   # fixed brick, small start error
    env = IE.InsertionEnv(stage=st, mode="residual", reward="sparse", vision=False, dr=False, seed=seed)
    env.reset()
    if brace == "all":
        own = {id(st) for st in env.cm.bricks["target"].conns}
        for st in env.cm.conn_states:
            if id(st) not in own:             # utilisation scales as 1 / f_break
                st.patch.coef /= BRACE_FACTOR
                st.patch.f_break *= BRACE_FACTOR
    th = np.random.default_rng(1000 + seed).uniform(0, 2 * math.pi)
    tx, _ = env.true_tgt
    env.believed = (tx + err_mm / 1000 * np.array([math.cos(th), math.sin(th), 0.0]), np.eye(3))
    m, d = env.m, env.d
    nbs = {m.body(n).id for n in ("nb0", "nb1", "nb2")} if layout == "pocket" else set()
    contacts, searched, done = 0, 0, False
    while not done:
        _, _, done, info = env.step(np.zeros(IE.ACT_DIM))
        searched += env.base.phase == "search"
        for c in d.contact[:d.ncon]:
            pair = {m.geom_bodyid[c.geom1], m.geom_bodyid[c.geom2]}
            contacts += env.bid in pair and bool(pair & nbs)
    return {"reason": info["reason"], "steps": info["steps"], "peak": info["peak_force_N"],
            "contacts": contacts, "search_steps": searched,
            "broken": sorted({e[2] for e in env.cm.breaks()})}


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--errors", type=float, nargs="+", default=[0, 1, 2, 3, 4], help="lateral aim error, mm")
    ap.add_argument("--seeds", type=int, default=6)
    ap.add_argument("--brace", nargs="+", default=["none"], choices=["none", "all"],
                    help="neighbour bracing stand-in, pocket only")
    args = ap.parse_args()
    lines = ["# Slot probe: scripted base, 2x4 brick, sparse episode outcome", "",
             "Generated by `Tanvir/slot_probe.py`. Aim error is the lateral offset of the believed target "
             "(random direction per seed); the scripted base aligns to it, descends, then spirals (2 mm, "
             "with a 1.5 deg wiggle) on contact. Contacts = brick-to-neighbour contact points summed over the episode.", "",
             "| socket | brace | aim error (mm) | seated | mean steps (20 Hz) | mean search steps | mean peak force (N) | mean neighbour contacts | outcomes | broken neighbours |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    runs = [("open", "none")] + [("pocket", b) for b in args.brace]
    for layout, brace in runs:
        for e in args.errors:
            rs = [episode(layout, e, s, brace) for s in range(args.seeds)]
            ok = sum(r["reason"] == "success" for r in rs)
            reasons = {}
            for r in rs:
                reasons[r["reason"]] = reasons.get(r["reason"], 0) + 1
            broken = {}
            for r in rs:
                for b in r["broken"]:
                    broken[b] = broken.get(b, 0) + 1
            line = "| %s | %s | %.1f | %d/%d | %.0f | %.0f | %.0f | %.0f | %s | %s |" % (
                layout, brace, e, ok, len(rs), np.mean([r["steps"] for r in rs]),
                np.mean([r["search_steps"] for r in rs]), np.mean([r["peak"] for r in rs]),
                np.mean([r["contacts"] for r in rs]), ", ".join("%s %d" % kv for kv in sorted(reasons.items())),
                ", ".join("%s x%d" % kv for kv in sorted(broken.items())) or "-")
            print(line, flush=True)
            lines.append(line)
    out = HERE / "results" / "slot_probe.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
